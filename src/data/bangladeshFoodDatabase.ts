/**
 * Resolves any food ID (legacy or current) to its canonical active database ID.
 */
export function getCanonicalFoodId(foodId: string): string {
  if (!foodId) return foodId;
  return LEGACY_FOOD_ID_MIGRATIONS[foodId] || foodId;
}

/**
 * Safe lookup that finds a food item by ID, automatically resolving legacy aliases.
 */
export function getFoodById(foodId: string): FoodItem | undefined {
  const canonicalId = getCanonicalFoodId(foodId);
  return BANGLADESH_FOOD_DATABASE.find(f => f.id === canonicalId);
}

/**
 * Safely migrates a PlannedFoodItem if it references a deprecated food ID,
 * updating its FoodItem and portion macros according to the canonical profile.
 */
export function migratePlannedFoodItem(item: PlannedFoodItem): PlannedFoodItem {
  if (!item || !item.foodItem) return item;
  const canonicalId = getCanonicalFoodId(item.foodItem.id);
  if (canonicalId === item.foodItem.id) {
    return item;
  }
  const canonicalFood = getFoodById(canonicalId);
  if (!canonicalFood) return item;

  const multiplier = item.portionMultiplier || 1.0;
  return {
    ...item,
    foodItem: canonicalFood,
    calories: Math.round((canonicalFood.calories || 0) * multiplier),
    proteinGrams: Number(((canonicalFood.proteinGrams || 0) * multiplier).toFixed(1)),
    carbsGrams: Number(((canonicalFood.carbsGrams || 0) * multiplier).toFixed(1)),
    fatGrams: Number(((canonicalFood.fatGrams || 0) * multiplier).toFixed(1)),
    fiberGrams: Number(((canonicalFood.fiberGrams || 0) * multiplier).toFixed(1)),
  };
}

/**
 * Safely migrates an entire DailyMealPlan, updating legacy food items to canonical items
 * and synchronizing meal and plan totals.
 */
export function migrateDailyMealPlan(plan: DailyMealPlan): DailyMealPlan {
  if (!plan || !plan.meals) return plan;

  let hasChanges = false;
  const migratedMeals = plan.meals.map(slot => {
    let slotChanged = false;
    const migratedItems = slot.items.map(item => {
      const canonicalId = getCanonicalFoodId(item.foodItem?.id);
      if (canonicalId !== item.foodItem?.id) {
        hasChanges = true;
        slotChanged = true;
        return migratePlannedFoodItem(item);
      }
      return item;
    });

    if (!slotChanged) return slot;

    const totalCalories = migratedItems.reduce((s, i) => s + i.calories, 0);
    const totalProteinGrams = Number(migratedItems.reduce((s, i) => s + i.proteinGrams, 0).toFixed(1));
    const totalCarbsGrams = Number(migratedItems.reduce((s, i) => s + i.carbsGrams, 0).toFixed(1));
    const totalFatGrams = Number(migratedItems.reduce((s, i) => s + i.fatGrams, 0).toFixed(1));
    const totalFiberGrams = Number(migratedItems.reduce((s, i) => s + i.fiberGrams, 0).toFixed(1));

    return {
      ...slot,
      items: migratedItems,
      totalCalories,
      totalProteinGrams,
      totalCarbsGrams,
      totalFatGrams,
      totalFiberGrams,
    };
  });

  if (!hasChanges) return plan;

  const actualTotalCalories = migratedMeals.reduce((s, m) => s + (m.isOptional ? 0 : m.totalCalories), 0);
  const totalProteinGrams = Number(migratedMeals.reduce((s, m) => s + (m.isOptional ? 0 : m.totalProteinGrams), 0).toFixed(1));
  const totalCarbsGrams = Number(migratedMeals.reduce((s, m) => s + (m.isOptional ? 0 : m.totalCarbsGrams), 0).toFixed(1));
  const totalFatGrams = Number(migratedMeals.reduce((s, m) => s + (m.isOptional ? 0 : m.totalFatGrams), 0).toFixed(1));
  const totalFiberGrams = Number(migratedMeals.reduce((s, m) => s + (m.isOptional ? 0 : m.totalFiberGrams), 0).toFixed(1));

  return {
    ...plan,
    meals: migratedMeals,
    actualTotalCalories,
    totalProteinGrams,
    totalCarbsGrams,
    totalFatGrams,
    totalFiberGrams,
  };
}

